"""Generate Concord's original CC0 reaction loops. Optional developer tool: Pillow."""
from pathlib import Path
import base64
import io
import json
import math
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
COLORS = [(30,31,46),(124,108,255),(248,113,113),(250,204,21),(52,211,153),(248,250,252),(251,146,60),(103,232,249)]
REACTIONS = [
    ('wave-v1', 'Привет!', ['привет','пока','hello','hi','wave','bye','эмоции']),
    ('heart-v1', 'Любовь', ['любовь','сердце','спасибо','love','heart','thanks','эмоции']),
    ('laugh-v1', 'Ха-ха', ['смех','смешно','ха','laugh','lol','happy','эмоции']),
    ('yes-v1', 'Отлично!', ['да','хорошо','круто','yes','ok','great','эмоции']),
    ('sparkle-v1', 'Вау!', ['вау','звезда','круто','wow','star','sparkle','эмоции']),
    ('fire-v1', 'Огонь', ['огонь','круто','fire','hot','trending','эмоции']),
]

def frame(kind, index):
    image = Image.new('P', (96,96), 0)
    palette = sum((list(color) for color in COLORS), [])
    image.putpalette(palette + [0]*(768-len(palette)))
    draw = ImageDraw.Draw(image)
    phase = math.sin(index*math.pi/4)
    if kind.startswith('heart'):
        size = 1 + .09*phase
        points = []
        for n in range(100):
            t = n*2*math.pi/100
            points.append((48+size*2.2*16*math.sin(t)**3,45-size*2.2*(13*math.cos(t)-5*math.cos(2*t)-2*math.cos(3*t)-math.cos(4*t))))
        draw.polygon(points, fill=2)
    elif kind.startswith('laugh'):
        y = int(5*abs(phase))
        draw.ellipse((16,13+y,80,77+y), fill=3)
        draw.arc((28,31+y,42,43+y),180,350,fill=0,width=4)
        draw.arc((54,31+y,68,43+y),180,350,fill=0,width=4)
        draw.arc((30,42+y,66,66+y),0,180,fill=0,width=5)
    elif kind.startswith('yes'):
        draw.ellipse((13,13,83,83),fill=4)
        draw.line([(29,48),(42,61),(69,33)],fill=5,width=9)
        if phase>0: draw.ellipse((76,6,83,13),fill=5)
    elif kind.startswith('sparkle'):
        radius = 25+int(8*phase)
        draw.polygon([(48,48-radius),(54,42),(48+radius,48),(54,54),(48,48+radius),(42,54),(48-radius,48),(42,42)],fill=3)
        draw.ellipse((14,17,20,23),fill=7)
        draw.ellipse((73,74,79,80),fill=1)
    elif kind.startswith('fire'):
        draw.polygon([(48,9),(60,31),(66,23),(80,57),(73,77),(49,86),(24,75),(17,55),(34,29),(35,45)],fill=6)
        draw.polygon([(48,37+int(4*phase)),(63,61),(58,76),(43,79),(32,67)],fill=3)
    else:
        offset = int(5*phase)
        draw.rounded_rectangle((29+offset,43,65+offset,79),radius=14,fill=3)
        for x,top in [(31,24),(41,15),(51,18),(61,28)]:
            draw.line([(x+offset,55),(x+offset,top)],fill=3,width=8)
        draw.line([(32+offset,63),(19+offset,45)],fill=3,width=9)
        draw.arc((8,8,85,87),200,250,fill=7,width=3)
        draw.arc((10,8,88,90),290,340,fill=7,width=3)
    return image

def main():
    result=[]
    for kind,title,tags in REACTIONS:
        frames=[frame(kind,n) for n in range(8)]
        output=io.BytesIO()
        frames[0].save(output,format='GIF',save_all=True,append_images=frames[1:],duration=100,loop=0,optimize=False)
        result.append(dict(id=kind,title=title,tags=tags+['reactions'],width=96,height=96,data=base64.b64encode(output.getvalue()).decode()))
    target=ROOT/'backend/src/services/gif/localCatalog.ts'
    target.write_text('// Original CC0 reaction loops. Generated by scripts/generate-local-gifs.py.\nexport const LOCAL_GIFS = '+json.dumps(result,ensure_ascii=False,indent=2)+' as const;\n',encoding='utf-8')
    print('Generated',len(result),'original reaction GIFs')

if __name__=='__main__': main()
